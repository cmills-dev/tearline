#!/usr/bin/env bash
# scripts/local-preview.sh: a local stand-in for the hosted preview.
#
#   bash scripts/local-preview.sh up [--live-ch] [--live-llm] [--no-build]
#   bash scripts/local-preview.sh status
#   bash scripts/local-preview.sh down
#   bash scripts/local-preview.sh psql [owner|app]     a shell on the database
#
# What "up" builds, in the shape production will have it:
#   - Postgres 16 (Homebrew postgresql@16), data under $PREVIEW_HOME, listening on 127.0.0.1 only.
#   - A non-superuser owner role, neondb_owner, as Neon hands out, that owns the database.
#   - scripts/db-migrate.ts as that owner: roles.sql, then 0001.., then app_user's password.
#   - The app built with `next build` and served with `next start` (NODE_ENV=production, so the
#     production readiness rules apply), connected as app_user through APP_DATABASE_URL.
#   - Fresh local secrets (AUTH_SECRET and the rest), generated once, kept in $PREVIEW_HOME/env.sh
#     with mode 600. Never Cam's, never in git.
#
# Live calls. By default every outside call is off: Companies House runs on the recorded
# fixtures (dataMode "fixtures") and the model is off (LLM_PROVIDER=none). --live-ch passes Cam's
# CH_API_KEY through from .env.local (free, rate limited). --live-llm passes the model key
# through and spends credit, so it is never the default.
#
# Nothing here touches Vercel, Neon or a remote. "down" stops both servers and keeps the data.

set -euo pipefail

PRODUCT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREVIEW_HOME="${PREVIEW_HOME:-$HOME/dev/tearline-preview}"
PGBIN="${PGBIN:-/opt/homebrew/opt/postgresql@16/bin}"
PG_PORT="${PREVIEW_PG_PORT:-54329}"
APP_PORT="${PREVIEW_APP_PORT:-3107}"
PGDATA="$PREVIEW_HOME/pgdata"
ENV_FILE="$PREVIEW_HOME/env.sh"
APP_PID="$PREVIEW_HOME/app.pid"
APP_LOG="$PREVIEW_HOME/app.log"
DB=tearline
HEAVY="${HEAVY:-$HOME/Documents/Claude/bin/heavy}"
[ -x "$HEAVY" ] || HEAVY=""

say() { printf 'local-preview: %s\n' "$*"; }
die() { say "$*" >&2; exit 1; }
rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }

ensure_secrets() {
  mkdir -p "$PREVIEW_HOME"
  if [ ! -f "$ENV_FILE" ]; then
    umask 077
    cat > "$ENV_FILE" <<EOF
# Local preview secrets. Generated by scripts/local-preview.sh. Local only, never reuse.
OWNER_PASSWORD='$(rand 32)'
APP_USER_PASSWORD='$(rand 32)'
AUTH_SECRET='$(rand 48)'
SHARED_HASH_PEPPER='$(rand 32)'
CRON_SECRET='$(rand 32)'
SHARED_ADMIN_SECRET='$(rand 32)'
SMOKE_EMAIL='smoke@preview.local'
SMOKE_PASSWORD='$(rand 24)'
EOF
    chmod 600 "$ENV_FILE"
    say "generated local secrets in $ENV_FILE"
  fi
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  OWNER_DATABASE_URL="postgres://neondb_owner:${OWNER_PASSWORD}@127.0.0.1:${PG_PORT}/${DB}"
  APP_DATABASE_URL="postgres://app_user:${APP_USER_PASSWORD}@127.0.0.1:${PG_PORT}/${DB}"
}

pg_running() { "$PGBIN/pg_ctl" -D "$PGDATA" status >/dev/null 2>&1; }
app_running() { [ -f "$APP_PID" ] && kill -0 "$(cat "$APP_PID")" 2>/dev/null; }
port_pids() { lsof -nP -iTCP:"$APP_PORT" -sTCP:LISTEN -t 2>/dev/null || true; }
superpsql() { "$PGBIN/psql" -h "$PREVIEW_HOME" -p "$PG_PORT" -U postgres -v ON_ERROR_STOP=1 -qAt "$@"; }

db_up() {
  [ -x "$PGBIN/initdb" ] || die "Postgres 16 not found at $PGBIN. brew install postgresql@16"
  if [ ! -f "$PGDATA/PG_VERSION" ]; then
    say "initdb in $PGDATA"
    # The superuser is reachable only through the unix socket in $PREVIEW_HOME. Every TCP login
    # (the owner and app_user, as the app and the migrations use) needs its password.
    "$PGBIN/initdb" -D "$PGDATA" -U postgres --auth-local=trust --auth-host=scram-sha-256 -E UTF8 --locale=C >/dev/null
  fi
  if ! pg_running; then
    LC_ALL=en_US.UTF-8 "$PGBIN/pg_ctl" -D "$PGDATA" -l "$PREVIEW_HOME/pg.log" -w \
      -o "-p $PG_PORT -k $PREVIEW_HOME -c listen_addresses=127.0.0.1" start >/dev/null
    say "postgres up on 127.0.0.1:$PG_PORT"
  fi
  # Neon's owner is not a superuser: it can create roles and owns the database. Same here, so
  # anything that only works as a superuser fails locally before it fails on Neon.
  if [ "$(superpsql -c "select 1 from pg_roles where rolname='neondb_owner'")" != "1" ]; then
    superpsql -c "create role neondb_owner login createrole password '${OWNER_PASSWORD}'"
  fi
  if [ "$(superpsql -c "select 1 from pg_database where datname='${DB}'")" != "1" ]; then
    superpsql -c "create database ${DB} owner neondb_owner"
  fi
  (cd "$PRODUCT_DIR" && OWNER_DATABASE_URL="$OWNER_DATABASE_URL" APP_USER_PASSWORD="$APP_USER_PASSWORD" \
    npx tsx scripts/db-migrate.ts --set-app-password)
}

app_env() {
  # Explicit values win over .env.local (Next never overrides a variable that is already set,
  # even to ""). So the defaults below switch Cam's live keys off for this process.
  export APP_DATABASE_URL AUTH_SECRET SHARED_HASH_PEPPER CRON_SECRET SHARED_ADMIN_SECRET
  export AUTH_REQUIRED=1 DATABASE_URL="" POSTGRES_URL="" PORT="$APP_PORT"
  if [ "$LIVE_CH" = 1 ]; then unset CH_API_KEY; else export CH_API_KEY=""; fi
  if [ "$LIVE_LLM" = 1 ]; then unset LLM_PROVIDER LLM_MODEL LLM_API_KEY; else export LLM_PROVIDER=none LLM_API_KEY=""; fi
}

cmd_up() {
  LIVE_CH=0; LIVE_LLM=0; BUILD=1
  for a in "$@"; do
    case "$a" in
      --live-ch) LIVE_CH=1 ;;
      --live-llm) LIVE_LLM=1; say "WARNING: --live-llm spends model credit on every read" ;;
      --no-build) BUILD=0 ;;
      *) die "unknown flag $a" ;;
    esac
  done
  ensure_secrets
  db_up
  app_running && { say "app already running (pid $(cat "$APP_PID")). down first to restart it."; cmd_status; return; }
  app_env
  cd "$PRODUCT_DIR"
  if [ "$BUILD" = 1 ] || [ ! -f .next/BUILD_ID ]; then
    say "next build"
    ${HEAVY:+$HEAVY} npx next build > "$PREVIEW_HOME/build.log" 2>&1 || { tail -30 "$PREVIEW_HOME/build.log"; die "build failed, log in $PREVIEW_HOME/build.log"; }
  fi
  nohup npx next start -p "$APP_PORT" -H 127.0.0.1 > "$APP_LOG" 2>&1 &
  echo $! > "$APP_PID"
  healthy=0
  for _ in $(seq 1 60); do
    if curl -sf "http://127.0.0.1:$APP_PORT/api/health" >/dev/null 2>&1; then healthy=1; break; fi
    sleep 1
  done
  [ "$healthy" = 1 ] || { tail -30 "$APP_LOG"; die "app did not answer /api/health in 60s, log in $APP_LOG"; }
  printf 'LIVE_CH=%s\nLIVE_LLM=%s\n' "$LIVE_CH" "$LIVE_LLM" > "$PREVIEW_HOME/mode"
  cmd_status
}

cmd_status() {
  if pg_running; then say "postgres: up on 127.0.0.1:$PG_PORT, data $PGDATA"; else say "postgres: down"; fi
  if app_running; then
    say "app: up on http://127.0.0.1:$APP_PORT (pid $(cat "$APP_PID")), log $APP_LOG"
    [ -f "$PREVIEW_HOME/mode" ] && say "mode: $(tr '\n' ' ' < "$PREVIEW_HOME/mode")"
    curl -s "http://127.0.0.1:$APP_PORT/api/health" || true; echo
  else
    say "app: down"
    stray="$(port_pids)"
    [ -z "$stray" ] || say "WARNING: something else listens on $APP_PORT (pid $(echo $stray | tr '\n' ' ')). Not ours: check it."
  fi
}

cmd_down() {
  if app_running; then
    # next start forks a child. Stop the whole group we started, then the pid itself.
    pkill -P "$(cat "$APP_PID")" 2>/dev/null || true
    kill "$(cat "$APP_PID")" 2>/dev/null || true
    say "app stopped"
  fi
  rm -f "$APP_PID"
  # A next-server orphaned by an earlier run (its parent gone, the port still held) is ours too if
  # it is a next-server. Anything else on the port is left alone and named.
  for p in $(port_pids); do
    if ps -o command= -p "$p" | grep -q "next-server"; then kill "$p" 2>/dev/null && say "stopped orphan next-server $p"; fi
  done
  if pg_running; then "$PGBIN/pg_ctl" -D "$PGDATA" -m fast -w stop >/dev/null; say "postgres stopped (data kept in $PGDATA)"; fi
}

cmd_psql() {
  ensure_secrets
  case "${1:-app}" in
    owner) exec "$PGBIN/psql" "$OWNER_DATABASE_URL" ;;
    app) exec "$PGBIN/psql" "$APP_DATABASE_URL" ;;
    *) die "psql owner|app" ;;
  esac
}

case "${1:-}" in
  up) shift; cmd_up "$@" ;;
  status) cmd_status ;;
  down) cmd_down ;;
  psql) shift; cmd_psql "$@" ;;
  *) sed -n '2,8p' "$0"; exit 2 ;;
esac
